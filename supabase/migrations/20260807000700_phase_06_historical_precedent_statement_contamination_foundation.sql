create or replace function private.historical_case_statement_contamination_metadata_valid(
  p_historical_value_only boolean,
  p_contamination_risk_level text,
  p_current_authority_disposition text
)
returns boolean
language sql
immutable
as $$
  select
    p_historical_value_only is not null
    and p_contamination_risk_level in ('low', 'medium', 'high')
    and p_current_authority_disposition in (
      'no_current_rule_implication',
      'check_phase_4',
      'check_phase_5',
      'check_phase_4_and_5',
      'potential_conflict_with_current_knowledge',
      'current_status_unknown'
    )
    and not (
      p_contamination_risk_level = 'high'
      and p_current_authority_disposition = 'no_current_rule_implication'
    );
$$;

