create table if not exists private.knowledge_embedding_models (
  id bigint generated by default as identity primary key,
  provider_code text not null,
  model_code text not null,
  model_version text,
  embedding_dimensions integer not null,
  config_fingerprint text not null,
  configuration_json jsonb not null default '{}'::jsonb,
  is_retrieval_approved boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint knowledge_embedding_models_provider_code_nonempty
    check (btrim(provider_code) <> ''),
  constraint knowledge_embedding_models_model_code_nonempty
    check (btrim(model_code) <> ''),
  constraint knowledge_embedding_models_model_version_nonempty
    check (model_version is null or btrim(model_version) <> ''),
  constraint knowledge_embedding_models_embedding_dimensions_positive
    check (embedding_dimensions > 0),
  constraint knowledge_embedding_models_config_fingerprint_nonempty
    check (btrim(config_fingerprint) <> ''),
  constraint knowledge_embedding_models_configuration_json_object
    check (jsonb_typeof(configuration_json) = 'object')
);

create unique index if not exists knowledge_embedding_models_registry_identity_idx
  on private.knowledge_embedding_models (
    provider_code,
    model_code,
    coalesce(model_version, ''),
    config_fingerprint
  );

create unique index if not exists knowledge_embedding_models_one_active_retrieval_model_idx
  on private.knowledge_embedding_models ((1))
  where is_retrieval_approved
    and is_active;

create table if not exists private.knowledge_embeddings (
  id bigint generated by default as identity primary key,
  chunk_id bigint not null references private.knowledge_chunks(id) on delete cascade,
  embedding_model_id bigint not null references private.knowledge_embedding_models(id) on delete restrict,
  input_content_hash text not null,
  generated_at timestamptz not null,
  embedding extensions.vector not null,
  created_at timestamptz not null default timezone('utc', now()),
  constraint knowledge_embeddings_input_content_hash_nonempty
    check (btrim(input_content_hash) <> ''),
  constraint knowledge_embeddings_unique_chunk_model_input
    unique (chunk_id, embedding_model_id, input_content_hash)
);

create index if not exists knowledge_embeddings_model_chunk_lookup_idx
  on private.knowledge_embeddings (embedding_model_id, chunk_id, input_content_hash);

create or replace function private.build_knowledge_chunk_embedding_input(
  p_document_title text,
  p_heading_path text,
  p_section_heading text,
  p_question_label text,
  p_body_text text
)
returns text
language sql
immutable
as $$
select concat_ws(
  E'\n\n',
  concat('Document: ', coalesce(p_document_title, '')),
  case
    when coalesce(nullif(btrim(p_heading_path), ''), nullif(btrim(p_section_heading), '')) is not null then
      concat('Section: ', coalesce(nullif(btrim(p_heading_path), ''), nullif(btrim(p_section_heading), '')))
    else null
  end,
  case
    when nullif(btrim(p_question_label), '') is not null then
      concat('Question: ', nullif(btrim(p_question_label), ''))
    else null
  end,
  coalesce(p_body_text, '')
);
$$;

create or replace function private.build_knowledge_chunk_embedding_input_hash(
  p_document_title text,
  p_heading_path text,
  p_section_heading text,
  p_question_label text,
  p_body_text text
)
returns text
language sql
immutable
as $$
select md5(
  private.build_knowledge_chunk_embedding_input(
    p_document_title,
    p_heading_path,
    p_section_heading,
    p_question_label,
    p_body_text
  )
);
$$;

