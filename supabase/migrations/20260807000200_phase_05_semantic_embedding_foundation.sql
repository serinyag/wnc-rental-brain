create or replace function private.validate_knowledge_embedding()
returns trigger
language plpgsql
as $$
declare
  expected_dimensions integer;
  actual_dimensions integer;
begin
  select kem.embedding_dimensions
  into expected_dimensions
  from private.knowledge_embedding_models kem
  where kem.id = new.embedding_model_id;

  if expected_dimensions is null then
    return new;
  end if;

  actual_dimensions := extensions.vector_dims(new.embedding);

  if actual_dimensions <> expected_dimensions then
    raise exception 'embedding dimensions % do not match model % dimensions %',
      actual_dimensions,
      new.embedding_model_id,
      expected_dimensions
      using errcode = '23514';
  end if;

  return new;
end;
$$;

create or replace function private.search_knowledge_chunks_semantic(
  p_query_embedding extensions.vector,
  p_result_limit integer default 10,
  p_embedding_model_id bigint default null,
  p_document_code text default null,
  p_category_code text default null,
  p_rental_type_code text default null
)
returns table (
  chunk_id bigint,
  document_code text,
  document_title text,
  document_version_id bigint,
  document_version_number integer,
  chunk_set_id bigint,
  chunk_ordinal integer,
  section_heading text,
  heading_path text,
  question_label text,
  body_text text,
  similarity_score double precision,
  cosine_distance double precision,
  content_hash text,
  input_content_hash text,
  embedding_model_id bigint,
  provider_code text,
  model_code text,
  model_version text,
  primary_chunk_source_id bigint,
  primary_document_version_source_object_id bigint,
  primary_source_locator text,
  primary_category_code text,
  rental_type_codes text[]
)
language plpgsql
stable
security invoker
set search_path = pg_catalog, private, public, extensions
as $$
declare
  resolved_embedding_model_id bigint;
  resolved_embedding_dimensions integer;
  approved_model_count integer;
  actual_query_dimensions integer;
  bounded_limit integer;
begin
  if p_query_embedding is null then
    raise exception 'query embedding is required'
      using errcode = '22004';
  end if;

  bounded_limit := least(greatest(coalesce(p_result_limit, 10), 1), 50);

  if p_embedding_model_id is null then
    select count(*)
    into approved_model_count
    from private.knowledge_embedding_models kem
    where kem.is_retrieval_approved
      and kem.is_active;

    if approved_model_count = 0 then
      raise exception 'no active retrieval-approved embedding model is registered'
        using errcode = 'P0001';
    end if;

    if approved_model_count > 1 then
      raise exception 'multiple active retrieval-approved embedding models are registered'
        using errcode = 'P0001';
    end if;

    select
      kem.id,
      kem.embedding_dimensions
    into resolved_embedding_model_id, resolved_embedding_dimensions
    from private.knowledge_embedding_models kem
    where kem.is_retrieval_approved
      and kem.is_active;
  else
    select
      kem.id,
      kem.embedding_dimensions
    into resolved_embedding_model_id, resolved_embedding_dimensions
    from private.knowledge_embedding_models kem
    where kem.id = p_embedding_model_id
      and kem.is_active;

    if resolved_embedding_model_id is null then
      raise exception 'embedding model % is not an active registered model',
        p_embedding_model_id
        using errcode = '23503';
    end if;
  end if;

  actual_query_dimensions := vector_dims(p_query_embedding);

  if actual_query_dimensions <> resolved_embedding_dimensions then
    raise exception 'query embedding dimensions % do not match model % dimensions %',
      actual_query_dimensions,
      resolved_embedding_model_id,
      resolved_embedding_dimensions
      using errcode = '23514';
  end if;

  return query
  with scored as (
    select
      ckei.chunk_id,
      ckei.document_code,
      ckei.document_title,
      ckei.document_version_id,
      ckei.document_version_number,
      ckei.chunk_set_id,
      ckei.chunk_ordinal,
      ckei.section_heading,
      ckei.heading_path,
      ckei.question_label,
      ckei.body_text,
      1 - (ke.embedding <=> p_query_embedding) as similarity_score,
      ke.embedding <=> p_query_embedding as cosine_distance,
      ckei.content_hash,
      ke.input_content_hash,
      kem.id as embedding_model_id,
      kem.provider_code,
      kem.model_code,
      kem.model_version,
      ckei.primary_chunk_source_id,
      ckei.primary_document_version_source_object_id,
      ckei.primary_source_locator,
      ckei.primary_category_code,
      ckei.rental_type_codes
    from private.current_knowledge_chunk_embedding_inputs ckei
    join private.knowledge_embeddings ke
      on ke.chunk_id = ckei.chunk_id
     and ke.embedding_model_id = resolved_embedding_model_id
     and ke.input_content_hash = ckei.embedding_input_hash
    join private.knowledge_embedding_models kem
      on kem.id = ke.embedding_model_id
    where (p_document_code is null or ckei.document_code = p_document_code)
      and (p_category_code is null or ckei.primary_category_code = p_category_code)
      and (
        p_rental_type_code is null
        or p_rental_type_code = any(coalesce(ckei.rental_type_codes, array[]::text[]))
      )
  )
  select
    scored.chunk_id,
    scored.document_code,
    scored.document_title,
    scored.document_version_id,
    scored.document_version_number,
    scored.chunk_set_id,
    scored.chunk_ordinal,
    scored.section_heading,
    scored.heading_path,
    scored.question_label,
    scored.body_text,
    scored.similarity_score,
    scored.cosine_distance,
    scored.content_hash,
    scored.input_content_hash,
    scored.embedding_model_id,
    scored.provider_code,
    scored.model_code,
    scored.model_version,
    scored.primary_chunk_source_id,
    scored.primary_document_version_source_object_id,
    scored.primary_source_locator,
    scored.primary_category_code,
    scored.rental_type_codes
  from scored
  order by scored.cosine_distance asc, scored.document_code, scored.chunk_ordinal
  limit bounded_limit;
end;
$$;

