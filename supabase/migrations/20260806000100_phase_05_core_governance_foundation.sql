create table if not exists public.logical_rules (
  rule_code text primary key,
  rule_domain text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint logical_rules_rule_code_nonempty check (btrim(rule_code) <> ''),
  constraint logical_rules_rule_domain_nonempty check (btrim(rule_domain) <> '')
);

create or replace function private.validate_rule_catalogue_logical_rule_domain()
returns trigger
language plpgsql
as $$
declare
  logical_rule_domain text;
begin
  select lr.rule_domain
  into logical_rule_domain
  from public.logical_rules lr
  where lr.rule_code = new.rule_code;

  if logical_rule_domain is not null and logical_rule_domain <> new.rule_domain then
    raise exception 'rule_code % must use logical rule domain %, not %', new.rule_code, logical_rule_domain, new.rule_domain
      using errcode = '23514';
  end if;

  return new;
end;
$$;

do $$
declare
  inconsistent_rule record;
begin
  select
    rc.rule_code,
    string_agg(distinct rc.rule_domain, ', ' order by rc.rule_domain) as domains
  into inconsistent_rule
  from public.rule_catalogue rc
  group by rc.rule_code
  having count(distinct rc.rule_domain) > 1
  limit 1;

  if found then
    raise exception 'logical_rules backfill blocked: rule_code % maps to multiple rule_domain values (%).',
      inconsistent_rule.rule_code,
      inconsistent_rule.domains
      using errcode = '23514';
  end if;
end;
$$;

insert into public.logical_rules (
  rule_code,
  rule_domain
)
select
  rc.rule_code,
  min(rc.rule_domain) as rule_domain
from public.rule_catalogue rc
group by rc.rule_code
on conflict (rule_code) do update
set rule_domain = excluded.rule_domain;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'rule_catalogue_rule_code_fkey'
      and conrelid = 'public.rule_catalogue'::regclass
  ) then
    alter table public.rule_catalogue
      add constraint rule_catalogue_rule_code_fkey
      foreign key (rule_code)
      references public.logical_rules(rule_code)
      on update restrict
      on delete restrict;
  end if;
end;
$$;

