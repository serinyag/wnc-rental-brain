create or replace function private.validate_knowledge_document_version_supersession()
returns trigger
language plpgsql
as $$
declare
  superseded_document_id bigint;
begin
  if new.supersedes_version_id is null then
    return new;
  end if;

  if new.id is not null and new.supersedes_version_id = new.id then
    raise exception 'knowledge document version cannot supersede itself'
      using errcode = '23514';
  end if;

  select kdv.document_id
  into superseded_document_id
  from public.knowledge_document_versions kdv
  where kdv.id = new.supersedes_version_id;

  if superseded_document_id is not null and superseded_document_id <> new.document_id then
    raise exception 'knowledge document version can only supersede a prior version from the same document'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

