create or replace function private.normalize_historical_case_source_locator(p_source_locator text)
returns text
language sql
immutable
as $$
  select lower(regexp_replace(btrim(p_source_locator), '\s+', ' ', 'g'));
$$;

create or replace function private.historical_case_evidence_support_dimensions_valid(p_support_dimensions text[])
returns boolean
language sql
immutable
as $$
  select
    p_support_dimensions is not null
    and cardinality(p_support_dimensions) > 0
    and p_support_dimensions <@ array[
      'identity',
      'date',
      'responsibility',
      'decision',
      'lesson',
      'context'
    ]::text[]
    and not exists (
      select 1
      from unnest(p_support_dimensions) as support_dimension
      where support_dimension is null
        or btrim(support_dimension) = ''
    )
    and cardinality(p_support_dimensions) = (
      select count(distinct support_dimension)
      from unnest(p_support_dimensions) as support_dimension
    );
$$;

create table if not exists public.historical_case_evidence_roles (
  id bigint generated by default as identity primary key,
  role_code text not null unique,
  display_name text not null,
  description text not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint historical_case_evidence_roles_code_nonempty
    check (btrim(role_code) <> ''),
  constraint historical_case_evidence_roles_display_name_nonempty
    check (btrim(display_name) <> ''),
  constraint historical_case_evidence_roles_description_nonempty
    check (btrim(description) <> ''),
  constraint historical_case_evidence_roles_sort_order_nonnegative
    check (sort_order >= 0)
);

create table if not exists public.historical_case_version_source_objects (
  id bigint generated by default as identity primary key,
  historical_case_version_id bigint not null references public.historical_case_versions(id) on delete cascade,
  source_object_id bigint not null references public.knowledge_source_objects(id) on delete restrict,
  evidence_role_id bigint not null references public.historical_case_evidence_roles(id) on delete restrict,
  confidentiality_level_id bigint not null references public.knowledge_confidentiality_levels(id) on delete restrict,
  evidence_strength text not null,
  source_locator text not null,
  supported_claim_dimensions text[] not null,
  relationship_notes text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint historical_case_version_source_objects_evidence_strength_check
    check (evidence_strength in ('strong', 'moderate', 'limited')),
  constraint historical_case_version_source_objects_source_locator_nonempty
    check (btrim(source_locator) <> ''),
  constraint hcvso_supported_claim_dimensions_check
    check (private.historical_case_evidence_support_dimensions_valid(supported_claim_dimensions)),
  constraint hcvso_relationship_notes_nonempty
    check (relationship_notes is null or btrim(relationship_notes) <> '')
);

