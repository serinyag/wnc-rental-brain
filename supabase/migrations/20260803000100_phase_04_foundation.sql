create or replace function private.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create or replace function private.normalize_rental_duration_hours(p_duration_minutes integer)
returns integer
language sql
immutable
as $$
  select case
    when p_duration_minutes is null or p_duration_minutes <= 0 then null
    else ceil(p_duration_minutes::numeric / 60.0)::integer
  end;
$$;

