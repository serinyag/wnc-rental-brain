create table if not exists public.rule_catalogue (
  id bigint generated by default as identity primary key,
  rule_code text not null,
  rule_domain text not null,
  rule_kind text not null,
  rule_version integer not null,
  status text not null,
  effective_from date,
  effective_until date,
  plain_language_explanation text not null,
  owner_role text,
  supersedes_rule_id bigint references public.rule_catalogue(id) on delete restrict,
  last_reviewed_at date,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint rule_catalogue_rule_code_nonempty check (btrim(rule_code) <> ''),
  constraint rule_catalogue_rule_domain_nonempty check (btrim(rule_domain) <> ''),
  constraint rule_catalogue_rule_kind_check check (rule_kind in ('hard_rule', 'conditional_rule')),
  constraint rule_catalogue_rule_version_positive check (rule_version > 0),
  constraint rule_catalogue_status_check check (status in ('draft', 'active', 'superseded', 'retired')),
  constraint rule_catalogue_date_range_check
