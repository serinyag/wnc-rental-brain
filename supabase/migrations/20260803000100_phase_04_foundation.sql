create or replace function private.validate_rule_supersession()
returns trigger
language plpgsql
as $$
declare
  superseded_code text;
begin
  if new.supersedes_rule_id is null then
    return new;
  end if;

  if new.id is not null and new.supersedes_rule_id = new.id then
    raise exception 'rule cannot supersede itself'
      using errcode = '23514';
  end if;

  select rule_code
  into superseded_code
  from public.rule_catalogue
  where id = new.supersedes_rule_id;

  if superseded_code is not null and superseded_code <> new.rule_code then
    raise exception 'rule can only supersede a prior version with the same rule_code'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

create or replace function private.enforce_rule_provenance_for_rule()
returns trigger
language plpgsql
as $$
begin
  if new.status in ('active', 'superseded', 'retired')
     and not exists (
       select 1
       from public.rule_source_links rsl
       where rsl.rule_id = new.id
         and rsl.relation_type in ('primary', 'governance')
     ) then
    raise exception 'rule % must have at least one primary or governance source link before commit', new.rule_code
      using errcode = '23514';
  end if;

  return null;
end;
$$;

create or replace function private.enforce_rule_provenance_for_link()
returns trigger
language plpgsql
as $$
declare
  target_rule_id bigint;
  target_status text;
  target_rule_code text;
begin
  target_rule_id := coalesce(new.rule_id, old.rule_id);

  select status, rule_code
  into target_status, target_rule_code
  from public.rule_catalogue
  where id = target_rule_id;

  if not found then
    return null;
  end if;

  if target_status in ('active', 'superseded', 'retired')
     and not exists (
       select 1
       from public.rule_source_links rsl
       where rsl.rule_id = target_rule_id
         and rsl.relation_type in ('primary', 'governance')
     ) then
    raise exception 'rule % must have at least one primary or governance source link before commit', target_rule_code
      using errcode = '23514';
  end if;

  return null;
end;
$$;

