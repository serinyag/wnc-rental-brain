create or replace function private.assert_hcv_current_authority_connectivity_valid(
  p_historical_case_version_id bigint,
  p_precedent_availability text,
  p_contains_historical_value_only_content boolean
)
returns void
language plpgsql
as $$
declare
  has_phase_4_relationship boolean;
  has_phase_5_relationship boolean;
  requires_phase_4 boolean;
  requires_phase_5 boolean;
  requires_phase_4_and_5 boolean;
  has_potential_conflict boolean;
  has_current_status_unknown boolean;
begin
  if p_historical_case_version_id is null then
    return;
  end if;

  select exists (
    select 1
    from public.historical_case_version_logical_rules hcvlr
    where hcvlr.historical_case_version_id = p_historical_case_version_id
    union all
    select 1
    from public.historical_case_version_rule_versions hcvrv
    where hcvrv.historical_case_version_id = p_historical_case_version_id
  )
  into has_phase_4_relationship;

  select exists (
    select 1
    from public.historical_case_version_knowledge_documents hcvkd
    where hcvkd.historical_case_version_id = p_historical_case_version_id
    union all
    select 1
    from public.historical_case_version_knowledge_document_versions hcvkdv
    where hcvkdv.historical_case_version_id = p_historical_case_version_id
  )
  into has_phase_5_relationship;

  select exists (
    select 1
    from public.historical_case_version_responsibilities hcvr
    where hcvr.historical_case_version_id = p_historical_case_version_id
      and hcvr.current_authority_disposition = 'check_phase_4'
    union all
    select 1
    from public.historical_case_version_decisions hcvd
    where hcvd.historical_case_version_id = p_historical_case_version_id
      and hcvd.current_authority_disposition = 'check_phase_4'
    union all
    select 1
    from public.historical_case_version_lessons hcvl
    where hcvl.historical_case_version_id = p_historical_case_version_id
      and hcvl.current_authority_disposition = 'check_phase_4'
  )
  into requires_phase_4;

  select exists (
    select 1
    from public.historical_case_version_responsibilities hcvr
    where hcvr.historical_case_version_id = p_historical_case_version_id
      and hcvr.current_authority_disposition = 'check_phase_5'
    union all
    select 1
    from public.historical_case_version_decisions hcvd
    where hcvd.historical_case_version_id = p_historical_case_version_id
      and hcvd.current_authority_disposition = 'check_phase_5'
    union all
    select 1
    from public.historical_case_version_lessons hcvl
    where hcvl.historical_case_version_id = p_historical_case_version_id
      and hcvl.current_authority_disposition = 'check_phase_5'
  )
  into requires_phase_5;

  select exists (
    select 1
    from public.historical_case_version_responsibilities hcvr
    where hcvr.historical_case_version_id = p_historical_case_version_id
      and hcvr.current_authority_disposition = 'check_phase_4_and_5'
    union all
    select 1
    from public.historical_case_version_decisions hcvd
    where hcvd.historical_case_version_id = p_historical_case_version_id
      and hcvd.current_authority_disposition = 'check_phase_4_and_5'
    union all
    select 1
    from public.historical_case_version_lessons hcvl
    where hcvl.historical_case_version_id = p_historical_case_version_id
      and hcvl.current_authority_disposition = 'check_phase_4_and_5'
  )
  into requires_phase_4_and_5;

  select exists (
    select 1
    from public.historical_case_version_responsibilities hcvr
    where hcvr.historical_case_version_id = p_historical_case_version_id
      and hcvr.current_authority_disposition = 'potential_conflict_with_current_knowledge'
    union all
    select 1
    from public.historical_case_version_decisions hcvd
    where hcvd.historical_case_version_id = p_historical_case_version_id
      and hcvd.current_authority_disposition = 'potential_conflict_with_current_knowledge'
    union all
    select 1
    from public.historical_case_version_lessons hcvl
    where hcvl.historical_case_version_id = p_historical_case_version_id
      and hcvl.current_authority_disposition = 'potential_conflict_with_current_knowledge'
  )
  into has_potential_conflict;

  select exists (
    select 1
    from public.historical_case_version_responsibilities hcvr
    where hcvr.historical_case_version_id = p_historical_case_version_id
      and hcvr.current_authority_disposition = 'current_status_unknown'
    union all
    select 1
    from public.historical_case_version_decisions hcvd
    where hcvd.historical_case_version_id = p_historical_case_version_id
      and hcvd.current_authority_disposition = 'current_status_unknown'
    union all
    select 1
    from public.historical_case_version_lessons hcvl
    where hcvl.historical_case_version_id = p_historical_case_version_id
      and hcvl.current_authority_disposition = 'current_status_unknown'
  )
  into has_current_status_unknown;

  if (requires_phase_4 or requires_phase_4_and_5) and not has_phase_4_relationship then
    raise exception 'historical case version % cannot become active because at least one governed statement requires Phase 4 current-authority connectivity',
      p_historical_case_version_id
      using errcode = '23514';
  end if;

  if (requires_phase_5 or requires_phase_4_and_5) and not has_phase_5_relationship then
    raise exception 'historical case version % cannot become active because at least one governed statement requires Phase 5 current-authority connectivity',
      p_historical_case_version_id
      using errcode = '23514';
  end if;

  if has_potential_conflict and not (has_phase_4_relationship or has_phase_5_relationship) then
    raise exception 'historical case version % cannot become active because potential_conflict_with_current_knowledge requires at least one current-authority relationship',
      p_historical_case_version_id
      using errcode = '23514';
  end if;

  if has_potential_conflict and not p_contains_historical_value_only_content then
    raise exception 'historical case version % cannot become active because potential_conflict_with_current_knowledge requires historical-value-only content to remain explicitly marked',
      p_historical_case_version_id
      using errcode = '23514';
  end if;

  if has_current_status_unknown and p_precedent_availability <> 'limited' then
    raise exception 'historical case version % cannot become active with current_status_unknown unless precedent_availability is limited',
      p_historical_case_version_id
      using errcode = '23514';
  end if;
end;
$$;

create or replace function private.enforce_historical_case_version_lifecycle()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'UPDATE' and new.id is not null then
    new.contains_historical_value_only_content :=
      private.historical_case_version_contains_historical_value_only_content(new.id);
  end if;

  if tg_op = 'UPDATE' then
    if old.governance_status = 'draft' and new.governance_status not in ('draft', 'active', 'retired') then
      raise exception 'draft historical case versions can only remain draft, become active, or be retired'
        using errcode = '23514';
    end if;

    if old.governance_status = 'active' and new.governance_status not in ('active', 'superseded', 'retired') then
      raise exception 'active historical case versions can only remain active, become superseded, or be retired'
        using errcode = '23514';
    end if;

    if old.governance_status = 'superseded' and new.governance_status not in ('superseded', 'retired') then
      raise exception 'superseded historical case versions cannot become draft or active again'
        using errcode = '23514';
    end if;

    if old.governance_status = 'retired' and new.governance_status <> 'retired' then
      raise exception 'retired historical case versions are immutable lifecycle endpoints'
        using errcode = '23514';
    end if;

    if old.governance_status <> 'draft' and (
      old.historical_case_id is distinct from new.historical_case_id
      or old.version_number is distinct from new.version_number
      or old.precedent_availability is distinct from new.precedent_availability
      or old.precedent_type is distinct from new.precedent_type
      or old.evidence_strength is distinct from new.evidence_strength
      or old.historical_event_status is distinct from new.historical_event_status
      or old.temporal_precision is distinct from new.temporal_precision
      or old.event_date_start is distinct from new.event_date_start
      or old.event_date_end is distinct from new.event_date_end
      or old.temporal_note is distinct from new.temporal_note
      or old.curated_narrative is distinct from new.curated_narrative
      or old.confidentiality_level_id is distinct from new.confidentiality_level_id
      or old.personal_information_status is distinct from new.personal_information_status
      or old.personal_information_notes is distinct from new.personal_information_notes
      or old.contains_historical_value_only_content is distinct from new.contains_historical_value_only_content
      or old.supersedes_version_id is distinct from new.supersedes_version_id
    ) then
      raise exception 'non-draft historical case versions cannot be materially rewritten; create a superseding version instead'
        using errcode = '23514';
    end if;
  end if;

  if new.governance_status = 'draft' and new.activated_at is not null then
    raise exception 'draft historical case versions cannot record activated_at'
      using errcode = '23514';
  end if;

  if new.governance_status = 'active' and new.activated_at is null then
    new.activated_at := timezone('utc', now());
  end if;

  if new.governance_status = 'active' then
    perform private.assert_historical_case_version_statement_provenance_complete(new.id);
    perform private.assert_hcv_current_authority_connectivity_valid(
      new.id,
      new.precedent_availability,
      new.contains_historical_value_only_content
    );
  end if;

  if new.governance_status = 'superseded' and new.activated_at is null then
    raise exception 'superseded historical case versions must retain an activated_at timestamp'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

