create or replace function private.enforce_hcv_authority_connectivity_editability()
returns trigger
language plpgsql
as $$
declare
  target_historical_case_version_id bigint := coalesce(new.historical_case_version_id, old.historical_case_version_id);
  target_governance_status text;
begin
  select hcv.governance_status
  into target_governance_status
  from public.historical_case_versions hcv
  where hcv.id = target_historical_case_version_id;

  if target_governance_status is not null and target_governance_status <> 'draft' then
    raise exception 'historical case current-authority connectivity is immutable once the parent case version is no longer draft'
      using errcode = '23514';
  end if;

  return coalesce(new, old);
end;
$$;

create or replace function private.assert_hcv_rule_version_parent_scope_complete(
  p_historical_case_version_id bigint
)
returns void
language plpgsql
as $$
declare
  missing_rule_code text;
  missing_rule_version_id bigint;
begin
  if p_historical_case_version_id is null then
    return;
  end if;

  select rc.rule_code, hcvrv.rule_version_id
  into missing_rule_code, missing_rule_version_id
  from public.historical_case_version_rule_versions hcvrv
  join public.rule_catalogue rc
    on rc.id = hcvrv.rule_version_id
  where hcvrv.historical_case_version_id = p_historical_case_version_id
    and not exists (
      select 1
      from public.historical_case_version_logical_rules hcvlr
      where hcvlr.historical_case_version_id = hcvrv.historical_case_version_id
        and hcvlr.rule_code = rc.rule_code
    )
  limit 1;

  if missing_rule_version_id is not null then
    raise exception 'historical case version % cannot link to exact rule version % because no stable logical-rule relationship exists for rule_code %',
      p_historical_case_version_id,
      missing_rule_version_id,
      missing_rule_code
      using errcode = '23514';
  end if;
end;
$$;

create or replace function private.assert_hcv_doc_version_parent_scope_complete(
  p_historical_case_version_id bigint
)
returns void
language plpgsql
as $$
declare
  missing_document_id bigint;
  missing_document_version_id bigint;
begin
  if p_historical_case_version_id is null then
    return;
  end if;

  select kdv.document_id, hcvkdv.knowledge_document_version_id
  into missing_document_id, missing_document_version_id
  from public.historical_case_version_knowledge_document_versions hcvkdv
  join public.knowledge_document_versions kdv
    on kdv.id = hcvkdv.knowledge_document_version_id
  where hcvkdv.historical_case_version_id = p_historical_case_version_id
    and not exists (
      select 1
      from public.historical_case_version_knowledge_documents hcvkd
      where hcvkd.historical_case_version_id = hcvkdv.historical_case_version_id
        and hcvkd.knowledge_document_id = kdv.document_id
    )
  limit 1;

  if missing_document_version_id is not null then
    raise exception 'historical case version % cannot link to exact knowledge document version % because no stable knowledge document relationship exists for document_id %',
      p_historical_case_version_id,
      missing_document_version_id,
      missing_document_id
      using errcode = '23514';
  end if;
end;
$$;

