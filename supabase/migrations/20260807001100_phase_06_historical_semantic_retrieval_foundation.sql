create table if not exists private.historical_case_embedding_models (
  id bigint generated by default as identity primary key,
  provider_code text not null,
  model_code text not null,
  model_version text,
  embedding_dimensions integer not null,
  config_fingerprint text not null,
  configuration_json jsonb not null default '{}'::jsonb,
  is_retrieval_approved boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint historical_case_embedding_models_provider_code_nonempty
    check (btrim(provider_code) <> ''),
  constraint historical_case_embedding_models_model_code_nonempty
    check (btrim(model_code) <> ''),
  constraint historical_case_embedding_models_model_version_nonempty
    check (model_version is null or btrim(model_version) <> ''),
  constraint historical_case_embedding_models_embedding_dimensions_positive
    check (embedding_dimensions > 0),
  constraint historical_case_embedding_models_config_fingerprint_nonempty
    check (btrim(config_fingerprint) <> ''),
  constraint historical_case_embedding_models_configuration_json_object
    check (jsonb_typeof(configuration_json) = 'object')
