create or replace function private.build_historical_case_search_unit_embedding_input(
  p_case_title text,
  p_case_code text,
  p_unit_type text,
  p_actor_type text,
  p_lesson_kind text,
  p_search_text text
)
returns text
language sql
immutable
as $$
select concat_ws(
  E'\n\n',
  concat('Case: ', coalesce(p_case_title, '')),
  case
    when nullif(btrim(p_case_code), '') is not null then
      concat('Case code: ', nullif(btrim(p_case_code), ''))
    else null
  end,
  case
    when nullif(btrim(p_unit_type), '') is not null then
      concat('Unit type: ', nullif(btrim(p_unit_type), ''))
    else null
  end,
  case
    when nullif(btrim(p_actor_type), '') is not null then
      concat('Actor type: ', nullif(btrim(p_actor_type), ''))
    else null
  end,
  case
    when nullif(btrim(p_lesson_kind), '') is not null then
      concat('Lesson kind: ', nullif(btrim(p_lesson_kind), ''))
    else null
  end,
  coalesce(p_search_text, '')
);
$$;

create or replace function private.build_historical_case_search_unit_embedding_input_hash(
  p_case_title text,
  p_case_code text,
  p_unit_type text,
  p_actor_type text,
  p_lesson_kind text,
  p_search_text text
