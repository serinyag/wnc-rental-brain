create or replace view private.current_historical_case_embedding_coverage as
with approved_models as (
  select
    hcem.id as embedding_model_id,
    hcem.provider_code,
    hcem.model_code,
    hcem.model_version,
    hcem.embedding_dimensions,
    hcem.config_fingerprint
  from private.historical_case_embedding_models hcem
  where hcem.is_retrieval_approved
    and hcem.is_active
),
eligible_inputs as (
  select *
  from private.current_historical_case_embedding_inputs
),
current_matches as (
  select
    am.embedding_model_id,
    ei.search_unit_id
  from approved_models am
  join eligible_inputs ei
    on true
  join private.historical_case_embeddings hce
    on hce.historical_case_search_unit_id = ei.search_unit_id
   and hce.embedding_model_id = am.embedding_model_id
   and hce.input_content_hash = ei.embedding_input_hash
  group by am.embedding_model_id, ei.search_unit_id
),
stale_units as (
  select
    am.embedding_model_id,
    ei.search_unit_id
  from approved_models am
  join eligible_inputs ei
    on true
  where not exists (
    select 1
    from private.historical_case_embeddings hce_current
    where hce_current.historical_case_search_unit_id = ei.search_unit_id
      and hce_current.embedding_model_id = am.embedding_model_id
      and hce_current.input_content_hash = ei.embedding_input_hash
  )
    and exists (
      select 1
      from private.historical_case_embeddings hce_stale
      where hce_stale.historical_case_search_unit_id = ei.search_unit_id
        and hce_stale.embedding_model_id = am.embedding_model_id
    )
),
all_model_rows as (
  select
    am.embedding_model_id,
    am.provider_code,
    am.model_code,
    am.model_version,
    am.embedding_dimensions,
    am.config_fingerprint,
    (select count(*)::bigint from eligible_inputs) as eligible_unit_count,
    (select count(*)::bigint from current_matches cm where cm.embedding_model_id = am.embedding_model_id) as current_embedding_count,
    (select count(*)::bigint from stale_units su where su.embedding_model_id = am.embedding_model_id) as stale_unit_count
  from approved_models am
)
select
  amr.embedding_model_id,
  amr.provider_code,
  amr.model_code,
  amr.model_version,
  amr.embedding_dimensions,
  amr.config_fingerprint,
  amr.eligible_unit_count,
  amr.current_embedding_count,
  amr.eligible_unit_count - amr.current_embedding_count as missing_unit_count,
  amr.stale_unit_count
from all_model_rows amr;

create or replace function private.validate_historical_case_embedding()
returns trigger
language plpgsql
as $$
declare
  expected_dimensions integer;
  actual_dimensions integer;
begin
  select hcem.embedding_dimensions
  into expected_dimensions
  from private.historical_case_embedding_models hcem
  where hcem.id = new.embedding_model_id;

  if expected_dimensions is null then
    return new;
  end if;

  actual_dimensions := extensions.vector_dims(new.embedding);

  if actual_dimensions <> expected_dimensions then
    raise exception 'embedding dimensions % do not match historical embedding model % dimensions %',
      actual_dimensions,
      new.embedding_model_id,
      expected_dimensions
      using errcode = '23514';
  end if;

  return new;
end;
$$;

create or replace function private.search_historical_case_units_semantic(
  p_query_embedding extensions.vector,
  p_result_limit integer default 10,
  p_embedding_model_id bigint default null,
  p_case_code text default null,
  p_unit_type text default null,
  p_precedent_availability text default null,
  p_precedent_type text default null,
  p_lesson_kind text default null,
  p_historical_value_only boolean default null,
  p_contamination_risk_level text default null
)
returns table (
  search_unit_id bigint,
  source_layer_role text,
  source_key text,
  unit_type text,
  search_text text,
  similarity_score double precision,
  cosine_distance double precision,
  input_content_hash text,
  historical_case_id bigint,
  historical_case_version_id bigint,
  case_code text,
  case_title text,
  precedent_type text,
  precedent_availability text,
  case_evidence_strength text,
  unit_evidence_strength text,
  actor_type text,
  lesson_kind text,
  historical_value_only boolean,
  contamination_risk_level text,
  current_authority_disposition text,
  case_contains_historical_value_only_content boolean,
  effective_confidentiality_level_id bigint,
  effective_confidentiality_level_code text,
  case_personal_information_status text,
  source_object_personal_information_status text,
  primary_historical_case_version_source_object_id bigint,
  primary_source_object_id bigint,
  primary_source_locator text,
  source_link_count bigint,
  responsibility_id bigint,
  decision_id bigint,
  lesson_id bigint,
  embedding_model_id bigint,
  provider_code text,
  model_code text,
  model_version text
)
language plpgsql
stable
security invoker
set search_path = pg_catalog, private, public, extensions
as $$
declare
  resolved_embedding_model_id bigint;
  resolved_embedding_dimensions integer;
  approved_model_count integer;
  actual_query_dimensions integer;
  bounded_limit integer;
  normalized_case_code text;
  normalized_unit_type text;
  normalized_precedent_availability text;
  normalized_precedent_type text;
  normalized_lesson_kind text;
  normalized_contamination_risk_level text;
begin
  if p_query_embedding is null then
    raise exception 'query embedding is required'
      using errcode = '22004';
  end if;

  bounded_limit := least(greatest(coalesce(p_result_limit, 10), 1), 50);
  normalized_case_code := nullif(upper(btrim(coalesce(p_case_code, ''))), '');
  normalized_unit_type := nullif(lower(btrim(coalesce(p_unit_type, ''))), '');
  normalized_precedent_availability := nullif(lower(btrim(coalesce(p_precedent_availability, ''))), '');
  normalized_precedent_type := nullif(lower(btrim(coalesce(p_precedent_type, ''))), '');
  normalized_lesson_kind := nullif(lower(btrim(coalesce(p_lesson_kind, ''))), '');
  normalized_contamination_risk_level := nullif(lower(btrim(coalesce(p_contamination_risk_level, ''))), '');

  if normalized_unit_type is not null
     and normalized_unit_type not in ('case_narrative', 'responsibility', 'decision', 'lesson') then
    raise exception 'unsupported historical unit_type filter: %', normalized_unit_type
      using errcode = '22023';
  end if;

  if normalized_precedent_availability is not null
     and normalized_precedent_availability not in ('active', 'limited') then
    raise exception 'unsupported historical precedent_availability filter: %', normalized_precedent_availability
      using errcode = '22023';
  end if;

  if normalized_precedent_type is not null
     and normalized_precedent_type not in ('full_case', 'limited_precedent', 'cautionary_precedent') then
    raise exception 'unsupported historical precedent_type filter: %', normalized_precedent_type
      using errcode = '22023';
  end if;

  if normalized_lesson_kind is not null
     and normalized_lesson_kind not in ('source_explicit', 'curated_lesson', 'analyst_inference', 'caution_warning') then
    raise exception 'unsupported historical lesson_kind filter: %', normalized_lesson_kind
      using errcode = '22023';
  end if;

  if normalized_contamination_risk_level is not null
     and normalized_contamination_risk_level not in ('low', 'medium', 'high') then
    raise exception 'unsupported historical contamination_risk_level filter: %', normalized_contamination_risk_level
      using errcode = '22023';
  end if;

  if p_embedding_model_id is null then
    select count(*)
    into approved_model_count
    from private.historical_case_embedding_models hcem
    where hcem.is_retrieval_approved
      and hcem.is_active;

    if approved_model_count = 0 then
      raise exception 'no active retrieval-approved historical embedding model is registered'
        using errcode = 'P0001';
    end if;

    if approved_model_count > 1 then
      raise exception 'multiple active retrieval-approved historical embedding models are registered'
        using errcode = 'P0001';
    end if;

    select
      hcem.id,
      hcem.embedding_dimensions
    into resolved_embedding_model_id, resolved_embedding_dimensions
    from private.historical_case_embedding_models hcem
    where hcem.is_retrieval_approved
      and hcem.is_active;
  else
    select
      hcem.id,
      hcem.embedding_dimensions
    into resolved_embedding_model_id, resolved_embedding_dimensions
    from private.historical_case_embedding_models hcem
    where hcem.id = p_embedding_model_id
      and hcem.is_active;

    if resolved_embedding_model_id is null then
      raise exception 'historical embedding model % is not an active registered model',
        p_embedding_model_id
        using errcode = '23503';
    end if;
  end if;

  actual_query_dimensions := vector_dims(p_query_embedding);

  if actual_query_dimensions <> resolved_embedding_dimensions then
    raise exception 'query embedding dimensions % do not match historical embedding model % dimensions %',
      actual_query_dimensions,
      resolved_embedding_model_id,
      resolved_embedding_dimensions
      using errcode = '23514';
  end if;

  return query
  with scored as (
    select
      chcei.search_unit_id,
      chcei.source_layer_role,
      chcei.source_key,
      chcei.unit_type,
      chcei.search_text,
      1 - (hce.embedding <=> p_query_embedding) as similarity_score,
      hce.embedding <=> p_query_embedding as cosine_distance,
      hce.input_content_hash,
      chcei.historical_case_id,
      chcei.historical_case_version_id,
      chcei.case_code,
      chcei.case_title,
      chcei.precedent_type,
      chcei.precedent_availability,
      chcei.case_evidence_strength,
      chcei.unit_evidence_strength,
      chcei.actor_type,
      chcei.lesson_kind,
      chcei.historical_value_only,
      chcei.contamination_risk_level,
      chcei.current_authority_disposition,
      chcei.case_contains_historical_value_only_content,
      chcei.effective_confidentiality_level_id,
      chcei.effective_confidentiality_level_code,
      chcei.case_personal_information_status,
      chcei.source_object_personal_information_status,
      chcei.primary_historical_case_version_source_object_id,
      chcei.primary_source_object_id,
      chcei.primary_source_locator,
      chcei.source_link_count,
      chcei.responsibility_id,
      chcei.decision_id,
      chcei.lesson_id,
      hcem.id as embedding_model_id,
      hcem.provider_code,
      hcem.model_code,
      hcem.model_version
    from private.current_historical_case_embedding_inputs chcei
    join private.historical_case_embeddings hce
      on hce.historical_case_search_unit_id = chcei.search_unit_id
     and hce.embedding_model_id = resolved_embedding_model_id
     and hce.input_content_hash = chcei.embedding_input_hash
    join private.historical_case_embedding_models hcem
      on hcem.id = hce.embedding_model_id
    where (normalized_case_code is null or chcei.case_code = normalized_case_code)
      and (normalized_unit_type is null or chcei.unit_type = normalized_unit_type)
      and (
        normalized_precedent_availability is null
        or chcei.precedent_availability = normalized_precedent_availability
      )
      and (
        normalized_precedent_type is null
        or chcei.precedent_type = normalized_precedent_type
      )
      and (
        normalized_lesson_kind is null
        or chcei.lesson_kind = normalized_lesson_kind
      )
      and (
        p_historical_value_only is null
        or chcei.historical_value_only = p_historical_value_only
      )
      and (
        normalized_contamination_risk_level is null
        or chcei.contamination_risk_level = normalized_contamination_risk_level
      )
  )
  select
    scored.search_unit_id,
    scored.source_layer_role,
    scored.source_key,
    scored.unit_type,
    scored.search_text,
    scored.similarity_score,
    scored.cosine_distance,
    scored.input_content_hash,
    scored.historical_case_id,
    scored.historical_case_version_id,
    scored.case_code,
    scored.case_title,
    scored.precedent_type,
    scored.precedent_availability,
    scored.case_evidence_strength,
    scored.unit_evidence_strength,
    scored.actor_type,
    scored.lesson_kind,
    scored.historical_value_only,
    scored.contamination_risk_level,
    scored.current_authority_disposition,
    scored.case_contains_historical_value_only_content,
    scored.effective_confidentiality_level_id,
    scored.effective_confidentiality_level_code,
    scored.case_personal_information_status,
    scored.source_object_personal_information_status,
    scored.primary_historical_case_version_source_object_id,
    scored.primary_source_object_id,
    scored.primary_source_locator,
    scored.source_link_count,
    scored.responsibility_id,
    scored.decision_id,
    scored.lesson_id,
    scored.embedding_model_id,
    scored.provider_code,
    scored.model_code,
    scored.model_version
  from scored
  order by scored.cosine_distance asc, scored.case_code, scored.unit_type, scored.search_unit_id
  limit bounded_limit;
end;
$$;

