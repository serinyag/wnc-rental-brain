create or replace function api.evaluate_technical_equipment_quantity(
  p_equipment_code text,
  p_requested_quantity integer
)
returns table (
  equipment_id bigint,
  equipment_code text,
  equipment_name text,
  equipment_category text,
  quantity_numeric integer,
  quantity_display text,
  availability_status text,
  exact_count_guaranteed boolean,
  requested_quantity integer,
  quantity_evaluation_status text,
  conditions_summary text,
  source_code text,
  source_title text
)
language plpgsql
stable
as $$
declare
  v_equipment_code text := nullif(btrim(coalesce(p_equipment_code, '')), '');
begin
  if v_equipment_code is null then
    raise exception 'p_equipment_code is required.'
      using errcode = '22023';
  end if;

  if p_requested_quantity is null or p_requested_quantity <= 0 then
    raise exception 'p_requested_quantity must be a positive integer.'
      using errcode = '22023';
  end if;

  return query
  with matched_equipment as (
    select *
    from public.current_technical_equipment_inventory ctei
    where ctei.equipment_code = v_equipment_code
  )
  select
    me.id as equipment_id,
    me.equipment_code,
    me.equipment_name,
    me.equipment_category,
    me.quantity_numeric,
    me.quantity_display,
    me.availability_status,
    me.exact_count_guaranteed,
    p_requested_quantity as requested_quantity,
    case
      when me.quantity_numeric is not null and p_requested_quantity > me.quantity_numeric then 'insufficient_quantity'
      when me.quantity_numeric is null or me.exact_count_guaranteed = false then 'requires_confirmation'
      else 'quantity_available'
    end as quantity_evaluation_status,
    me.conditions_summary,
    me.source_code,
    me.source_title
  from matched_equipment me;

  if found then
    return;
  end if;

  return query
  select
    null::bigint as equipment_id,
    v_equipment_code as equipment_code,
    null::text as equipment_name,
    null::text as equipment_category,
    null::integer as quantity_numeric,
    null::text as quantity_display,
    null::text as availability_status,
    null::boolean as exact_count_guaranteed,
    p_requested_quantity as requested_quantity,
    'no_applicable_equipment'::text as quantity_evaluation_status,
    null::text as conditions_summary,
    null::text as source_code,
    null::text as source_title;
end;
$$;

create or replace function api.get_technical_capability(
  p_rule_type text default null,
  p_capability_code text default null,
  p_requirement_code text default null,
  p_technical_area text default null,
  p_as_of_date date default current_date
)
returns table (
  rule_id bigint,
  rule_code text,
  rule_version integer,
  status text,
  effective_from date,
  effective_until date,
  plain_language_explanation text,
  rule_type text,
  technical_area text,
  capability_code text,
  requirement_code text,
  equipment_inventory_id bigint,
  equipment_code text,
  equipment_name text,
  support_status text,
  included_in_base_rental boolean,
  internal_equipment_exists boolean,
  internal_support_sufficient boolean,
  client_may_self_organise boolean,
  wnc_can_coordinate boolean,
  coordination_fee_possible boolean,
  requires_confirmation boolean,
  manual_review_required boolean,
  conditions_summary text,
  applicability_status text,
  primary_source_codes text[],
  governance_source_codes text[],
  supporting_source_codes text[]
)
language plpgsql
stable
as $$
declare
  v_rule_type text := nullif(btrim(coalesce(p_rule_type, '')), '');
  v_capability_code text := nullif(btrim(coalesce(p_capability_code, '')), '');
  v_requirement_code text := nullif(btrim(coalesce(p_requirement_code, '')), '');
  v_technical_area text := nullif(btrim(coalesce(p_technical_area, '')), '');
  v_as_of_date date := coalesce(p_as_of_date, current_date);
  v_has_matches boolean := false;
begin
  if v_capability_code is not null and v_requirement_code is not null then
    raise exception 'Provide either p_capability_code or p_requirement_code, not both.'
      using errcode = '22023';
  end if;

  select exists (
    select 1
    from public.technical_capability_rules tcr
    join public.rule_catalogue rc
      on rc.id = tcr.rule_id
    where rc.status in ('active', 'superseded', 'retired')
      and (rc.effective_from is null or rc.effective_from <= v_as_of_date)
      and (rc.effective_until is null or rc.effective_until >= v_as_of_date)
      and (v_rule_type is null or tcr.rule_type = v_rule_type)
      and (v_technical_area is null or tcr.technical_area = v_technical_area)
      and (v_capability_code is null or tcr.capability_code = v_capability_code)
      and (v_requirement_code is null or tcr.requirement_code = v_requirement_code)
  )
  into v_has_matches;

  if v_has_matches then
    return query
    select
      rc.id as rule_id,
      rc.rule_code,
      rc.rule_version,
      rc.status,
      rc.effective_from,
      rc.effective_until,
      rc.plain_language_explanation,
      tcr.rule_type,
      tcr.technical_area,
      tcr.capability_code,
      tcr.requirement_code,
      tcr.equipment_inventory_id,
      tei.equipment_code,
      tei.equipment_name,
      tcr.support_status,
      tcr.included_in_base_rental,
      tcr.internal_equipment_exists,
      tcr.internal_support_sufficient,
      tcr.client_may_self_organise,
      tcr.wnc_can_coordinate,
      tcr.coordination_fee_possible,
      tcr.requires_confirmation,
      tcr.manual_review_required,
      tcr.conditions_summary,
      'applies'::text as applicability_status,
      coalesce(src.primary_source_codes, array[]::text[]) as primary_source_codes,
      coalesce(src.governance_source_codes, array[]::text[]) as governance_source_codes,
      coalesce(src.supporting_source_codes, array[]::text[]) as supporting_source_codes
    from public.technical_capability_rules tcr
    join public.rule_catalogue rc
      on rc.id = tcr.rule_id
    left join public.technical_equipment_inventory tei
      on tei.id = tcr.equipment_inventory_id
    left join lateral (
      select
        array_agg(distinct sr.source_code order by sr.source_code)
          filter (where rsl.relation_type = 'primary') as primary_source_codes,
        array_agg(distinct sr.source_code order by sr.source_code)
          filter (where rsl.relation_type = 'governance') as governance_source_codes,
        array_agg(distinct sr.source_code order by sr.source_code)
          filter (where rsl.relation_type = 'supporting') as supporting_source_codes
      from public.rule_source_links rsl
      join public.source_registry sr
        on sr.id = rsl.source_id
      where rsl.rule_id = rc.id
    ) src on true
    where rc.status in ('active', 'superseded', 'retired')
      and (rc.effective_from is null or rc.effective_from <= v_as_of_date)
      and (rc.effective_until is null or rc.effective_until >= v_as_of_date)
      and (v_rule_type is null or tcr.rule_type = v_rule_type)
      and (v_technical_area is null or tcr.technical_area = v_technical_area)
      and (v_capability_code is null or tcr.capability_code = v_capability_code)
      and (v_requirement_code is null or tcr.requirement_code = v_requirement_code)
    order by
      tcr.rule_type,
      tcr.technical_area,
      coalesce(tcr.capability_code, tcr.requirement_code),
      rc.rule_code;
    return;
  end if;

  return query
  select
    null::bigint as rule_id,
    null::text as rule_code,
    null::integer as rule_version,
    null::text as status,
    null::date as effective_from,
    null::date as effective_until,
    null::text as plain_language_explanation,
    v_rule_type as rule_type,
    v_technical_area as technical_area,
    v_capability_code as capability_code,
    v_requirement_code as requirement_code,
    null::bigint as equipment_inventory_id,
    null::text as equipment_code,
    null::text as equipment_name,
    null::text as support_status,
    null::boolean as included_in_base_rental,
    null::boolean as internal_equipment_exists,
    null::boolean as internal_support_sufficient,
    null::boolean as client_may_self_organise,
    null::boolean as wnc_can_coordinate,
    null::boolean as coordination_fee_possible,
    null::boolean as requires_confirmation,
    null::boolean as manual_review_required,
    null::text as conditions_summary,
    case
      when v_rule_type = 'capability_availability' and v_capability_code is null then 'insufficient_information'
      when v_rule_type = 'requirement_support' and v_requirement_code is null then 'insufficient_information'
      when v_rule_type is null and v_capability_code is null and v_requirement_code is null then 'insufficient_information'
      else 'no_applicable_rule'
    end as applicability_status,
    array[]::text[] as primary_source_codes,
    array[]::text[] as governance_source_codes,
    array[]::text[] as supporting_source_codes;
end;
$$;

