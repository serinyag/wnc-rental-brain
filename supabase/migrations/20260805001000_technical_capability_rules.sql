create or replace function private.assert_technical_capability_rule_integrity(p_rule_id bigint)
returns void
language plpgsql
as $$
declare
  current_rule record;
begin
  select
    rc.rule_code,
    rc.rule_domain,
    rc.rule_kind,
    rc.status,
    rc.effective_from,
    rc.effective_until,
    tcr.rule_type,
    tcr.technical_area,
    tcr.capability_code,
    tcr.requirement_code
  into current_rule
  from public.rule_catalogue rc
  join public.technical_capability_rules tcr
    on tcr.rule_id = rc.id
  where rc.id = p_rule_id;

  if not found then
    return;
  end if;

  if current_rule.rule_domain <> 'technical_capability' then
    raise exception 'technical_capability_rules row % must reference rule_domain technical_capability', p_rule_id
      using errcode = '23514';
  end if;

  if current_rule.rule_kind not in ('hard_rule', 'conditional_rule') then
    raise exception 'technical_capability_rules row % must reference a technical_capability hard_rule or conditional_rule', p_rule_id
      using errcode = '23514';
  end if;

  if current_rule.status = 'draft' then
    return;
  end if;

  if exists (
    select 1
    from public.technical_capability_rules other_tcr
    join public.rule_catalogue other_rc
      on other_rc.id = other_tcr.rule_id
    where other_tcr.rule_id <> p_rule_id
      and other_rc.status in ('active', 'superseded', 'retired')
      and other_tcr.rule_type = current_rule.rule_type
      and other_tcr.technical_area = current_rule.technical_area
      and other_tcr.capability_code is not distinct from current_rule.capability_code
      and other_tcr.requirement_code is not distinct from current_rule.requirement_code
      and private.date_windows_overlap(
        current_rule.effective_from,
        current_rule.effective_until,
        other_rc.effective_from,
        other_rc.effective_until
      )
  ) then
    raise exception 'overlapping technical capability rules detected for rule %', current_rule.rule_code
      using errcode = '23514';
  end if;
end;
$$;

create or replace function private.validate_technical_capability_rule_row()
returns trigger
language plpgsql
as $$
begin
  perform private.assert_technical_capability_rule_integrity(new.rule_id);
  return new;
end;
$$;

create or replace function private.validate_technical_capability_rule_catalogue()
returns trigger
language plpgsql
as $$
begin
  perform private.assert_technical_capability_rule_integrity(new.id);
  return new;
end;
$$;

