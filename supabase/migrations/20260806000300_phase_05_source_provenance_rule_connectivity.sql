create or replace function private.validate_knowledge_rule_relationship_target_kind()
returns trigger
language plpgsql
as $$
declare
  actual_target_kind text;
  relationship_code text;
  expected_target_kind text := tg_argv[0];
begin
  select krt.target_kind, krt.relationship_type_code
  into actual_target_kind, relationship_code
  from public.knowledge_rule_relationship_types krt
  where krt.id = new.relationship_type_id;

  if actual_target_kind is not null and actual_target_kind <> expected_target_kind then
    raise exception 'relationship type % must target %, not %',
      relationship_code,
      expected_target_kind,
      actual_target_kind
      using errcode = '23514';
  end if;

  return new;
end;
$$;

