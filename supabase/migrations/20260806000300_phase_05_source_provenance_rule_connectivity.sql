create table if not exists public.knowledge_source_objects (
  id bigint generated by default as identity primary key,
  source_registry_id bigint references public.source_registry(id) on delete restrict,
  origin_type text not null,
  external_uri text,
  repository_relative_path text,
  storage_bucket text,
  storage_object_key text,
  manual_reference_key text,
  original_filename text,
  mime_type text,
  file_size_bytes bigint,
  checksum_sha256 text,
  personal_information_status text not null default 'unknown',
  personal_information_notes text,
  imported_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint knowledge_source_objects_origin_type_check
    check (origin_type in ('repository_file', 'supabase_storage', 'external_uri', 'manual_reference')),
  constraint knowledge_source_objects_personal_information_status_check
    check (personal_information_status in ('yes', 'no', 'unknown')),
  constraint knowledge_source_objects_file_size_nonnegative
    check (file_size_bytes is null or file_size_bytes >= 0),
  constraint knowledge_source_objects_external_uri_nonempty
    check (external_uri is null or btrim(external_uri) <> ''),
  constraint knowledge_source_objects_repository_relative_path_nonempty
    check (repository_relative_path is null or btrim(repository_relative_path) <> ''),
  constraint knowledge_source_objects_storage_bucket_nonempty
    check (storage_bucket is null or btrim(storage_bucket) <> ''),
  constraint knowledge_source_objects_storage_object_key_nonempty
    check (storage_object_key is null or btrim(storage_object_key) <> ''),
  constraint knowledge_source_objects_manual_reference_key_nonempty
    check (manual_reference_key is null or btrim(manual_reference_key) <> ''),
  constraint knowledge_source_objects_original_filename_nonempty
    check (original_filename is null or btrim(original_filename) <> ''),
  constraint knowledge_source_objects_mime_type_nonempty
    check (mime_type is null or btrim(mime_type) <> ''),
  constraint knowledge_source_objects_checksum_sha256_nonempty
    check (checksum_sha256 is null or btrim(checksum_sha256) <> ''),
  constraint knowledge_source_objects_personal_information_notes_nonempty
    check (personal_information_notes is null or btrim(personal_information_notes) <> ''),
  constraint knowledge_source_objects_origin_locator_check
    check (
      (
        origin_type = 'repository_file'
        and repository_relative_path is not null
        and storage_bucket is null
        and storage_object_key is null
        and external_uri is null
        and manual_reference_key is null
      )
      or (
        origin_type = 'supabase_storage'
        and storage_bucket is not null
        and storage_object_key is not null
        and repository_relative_path is null
        and external_uri is null
        and manual_reference_key is null
      )
      or (
        origin_type = 'external_uri'
        and external_uri is not null
        and repository_relative_path is null
        and storage_bucket is null
        and storage_object_key is null
        and manual_reference_key is null
      )
      or (
        origin_type = 'manual_reference'
        and manual_reference_key is not null
        and repository_relative_path is null
        and storage_bucket is null
        and storage_object_key is null
        and external_uri is null
      )
    )
);

