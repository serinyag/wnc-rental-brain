  constraint knowledge_source_object_roles_display_name_nonempty check (btrim(display_name) <> ''),
  constraint knowledge_source_object_roles_description_nonempty check (btrim(description) <> ''),
  constraint knowledge_source_object_roles_sort_order_nonnegative check (sort_order >= 0)
