create or replace function private.validate_historical_case_search_unit()
returns trigger
language plpgsql
as $$
declare
  parent_case_id bigint;
  expected_source_key text;
  linked_version_id bigint;
begin
  select hcv.historical_case_id
  into parent_case_id
  from public.historical_case_versions hcv
  where hcv.id = new.historical_case_version_id;

  if parent_case_id is null then
    return new;
  end if;

  if parent_case_id <> new.historical_case_id then
    raise exception 'historical search unit case % does not match parent historical case version % case %',
      new.historical_case_id,
      new.historical_case_version_id,
      parent_case_id
      using errcode = '23514';
  end if;

  expected_source_key := private.historical_case_search_unit_expected_source_key(
    new.unit_type,
    new.historical_case_version_id,
    new.responsibility_id,
    new.decision_id,
    new.lesson_id
  );

  if expected_source_key is null or new.source_key <> expected_source_key then
    raise exception 'historical search unit source_key % does not match the controlled source identity for unit type %',
      new.source_key,
      new.unit_type
      using errcode = '23514';
  end if;

  if new.responsibility_id is not null then
    select hcvr.historical_case_version_id
    into linked_version_id
    from public.historical_case_version_responsibilities hcvr
    where hcvr.id = new.responsibility_id;

    if linked_version_id <> new.historical_case_version_id then
      raise exception 'responsibility-backed historical search unit must remain within one historical case version'
        using errcode = '23514';
    end if;
  end if;

  if new.decision_id is not null then
    select hcvd.historical_case_version_id
    into linked_version_id
    from public.historical_case_version_decisions hcvd
    where hcvd.id = new.decision_id;

    if linked_version_id <> new.historical_case_version_id then
      raise exception 'decision-backed historical search unit must remain within one historical case version'
        using errcode = '23514';
    end if;
  end if;

  if new.lesson_id is not null then
    select hcvl.historical_case_version_id
    into linked_version_id
    from public.historical_case_version_lessons hcvl
    where hcvl.id = new.lesson_id;

    if linked_version_id <> new.historical_case_version_id then
      raise exception 'lesson-backed historical search unit must remain within one historical case version'
        using errcode = '23514';
    end if;
  end if;

  return new;
end;
$$;

create or replace function private.validate_historical_case_unit_source()
returns trigger
language plpgsql
as $$
declare
  unit_record private.historical_case_search_units%rowtype;
  source_object_version_id bigint;
  linked_version_id bigint;
  linked_source_object_id bigint;
begin
  select *
  into unit_record
  from private.historical_case_search_units hcsu
  where hcsu.id = new.historical_case_search_unit_id;

  if not found then
    return new;
  end if;

  select hcvso.historical_case_version_id
  into source_object_version_id
  from public.historical_case_version_source_objects hcvso
  where hcvso.id = new.historical_case_version_source_object_id;

  if source_object_version_id <> unit_record.historical_case_version_id then
    raise exception 'historical unit lineage source object must belong to the same historical case version as the search unit'
      using errcode = '23514';
  end if;

  if unit_record.unit_type = 'case_narrative' then
    if new.responsibility_source_id is not null
       or new.decision_source_id is not null
       or new.lesson_source_id is not null then
      raise exception 'case_narrative units must trace directly to case-version evidence associations'
        using errcode = '23514';
    end if;

    return new;
  end if;

  if unit_record.unit_type = 'responsibility' then
    if new.responsibility_source_id is null
       or new.decision_source_id is not null
       or new.lesson_source_id is not null then
      raise exception 'responsibility units must trace through responsibility provenance only'
        using errcode = '23514';
    end if;

    select
      hcvrs.historical_case_version_id,
      hcvrs.historical_case_version_source_object_id
    into linked_version_id, linked_source_object_id
    from public.historical_case_version_responsibility_sources hcvrs
    where hcvrs.id = new.responsibility_source_id;

    if linked_version_id <> unit_record.historical_case_version_id
       or linked_source_object_id <> new.historical_case_version_source_object_id then
      raise exception 'responsibility unit lineage must resolve to the same version-scoped evidence association'
        using errcode = '23514';
    end if;

    return new;
  end if;

  if unit_record.unit_type = 'decision' then
    if new.responsibility_source_id is not null
       or new.decision_source_id is null
       or new.lesson_source_id is not null then
      raise exception 'decision units must trace through decision provenance only'
        using errcode = '23514';
    end if;

    select
      hcvds.historical_case_version_id,
      hcvds.historical_case_version_source_object_id
    into linked_version_id, linked_source_object_id
    from public.historical_case_version_decision_sources hcvds
    where hcvds.id = new.decision_source_id;

    if linked_version_id <> unit_record.historical_case_version_id
       or linked_source_object_id <> new.historical_case_version_source_object_id then
      raise exception 'decision unit lineage must resolve to the same version-scoped evidence association'
        using errcode = '23514';
    end if;

    return new;
  end if;

  if unit_record.unit_type = 'lesson' then
    if new.responsibility_source_id is not null
       or new.decision_source_id is not null
       or new.lesson_source_id is null then
      raise exception 'lesson units must trace through lesson provenance only'
        using errcode = '23514';
    end if;

    select
      hcvls.historical_case_version_id,
      hcvls.historical_case_version_source_object_id
    into linked_version_id, linked_source_object_id
    from public.historical_case_version_lesson_sources hcvls
    where hcvls.id = new.lesson_source_id;

    if linked_version_id <> unit_record.historical_case_version_id
       or linked_source_object_id <> new.historical_case_version_source_object_id then
      raise exception 'lesson unit lineage must resolve to the same version-scoped evidence association'
        using errcode = '23514';
    end if;

    return new;
  end if;

  return new;
end;
$$;

create or replace function private.assert_historical_case_search_unit_has_sources(
  p_historical_case_search_unit_id bigint
)
returns void
language plpgsql
as $$
declare
  source_count bigint;
begin
  if p_historical_case_search_unit_id is null then
    return;
  end if;

  select count(*)
  into source_count
  from private.historical_case_unit_sources hcus
  where hcus.historical_case_search_unit_id = p_historical_case_search_unit_id;

  if source_count = 0 then
    raise exception 'historical search unit % must retain at least one provenance lineage row',
      p_historical_case_search_unit_id
      using errcode = '23514';
  end if;
end;
$$;

create or replace function private.enforce_historical_case_search_unit_has_sources_from_unit()
returns trigger
language plpgsql
as $$
begin
  perform private.assert_historical_case_search_unit_has_sources(new.id);
  return null;
end;
$$;

create or replace function private.enforce_historical_case_search_unit_has_sources_from_unit_source()
returns trigger
language plpgsql
as $$
begin
  if tg_op in ('DELETE', 'UPDATE') then
    perform private.assert_historical_case_search_unit_has_sources(old.historical_case_search_unit_id);
  end if;

  if tg_op = 'UPDATE' then
    perform private.assert_historical_case_search_unit_has_sources(new.historical_case_search_unit_id);
  end if;

  return null;
end;
$$;

create or replace function private.rebuild_historical_case_search_units_for_version(
  p_historical_case_version_id bigint
)
returns bigint
language plpgsql
as $$
declare
  version_record record;
  rebuild_started_at timestamptz := timezone('utc', now());
  generated_unit_count bigint := 0;
begin
  insert into private.historical_case_version_processing (
    historical_case_version_id,
    search_unit_generation_status
  )
  values (
    p_historical_case_version_id,
    'not_started'
  )
  on conflict (historical_case_version_id) do nothing;

  update private.historical_case_version_processing
  set search_unit_generation_status = 'in_progress',
      last_attempted_at = rebuild_started_at,
      last_error_code = null,
      last_error_message = null
  where historical_case_version_id = p_historical_case_version_id;

  select
    hcv.id as historical_case_version_id,
    hcv.historical_case_id,
    hc.case_code,
    hc.canonical_title,
    hcv.governance_status,
    hcv.precedent_availability,
    hcv.precedent_type,
    hcv.evidence_strength,
    hcv.curated_narrative,
    hcv.confidentiality_level_id,
    hcv.personal_information_status,
    hcv.contains_historical_value_only_content
  into version_record
  from public.historical_case_versions hcv
  join public.historical_cases hc
    on hc.id = hcv.historical_case_id
  where hcv.id = p_historical_case_version_id;

  if not found then
    raise exception 'historical case version % does not exist', p_historical_case_version_id
      using errcode = '23503';
  end if;

  if version_record.governance_status <> 'active'
     or version_record.precedent_availability not in ('active', 'limited') then
    update private.historical_case_version_processing
    set search_unit_generation_status = 'not_applicable',
        last_succeeded_at = rebuild_started_at
    where historical_case_version_id = p_historical_case_version_id;

    return 0;
  end if;

  if not exists (
    select 1
    from public.historical_case_version_source_objects hcvso
    where hcvso.historical_case_version_id = p_historical_case_version_id
  ) then
    raise exception 'active historical case version % cannot materialize search units without at least one case-version evidence association',
      p_historical_case_version_id
      using errcode = '23514';
  end if;

  with narrative_source_meta as (
    select
      hcvso.historical_case_version_id,
      private.strictest_knowledge_confidentiality_level_id(
        array_append(array_agg(distinct hcvso.confidentiality_level_id), version_record.confidentiality_level_id)
      ) as effective_confidentiality_level_id,
      private.strictest_personal_information_status(
        array_agg(distinct kso.personal_information_status)
      ) as source_object_personal_information_status
    from public.historical_case_version_source_objects hcvso
    join public.knowledge_source_objects kso
      on kso.id = hcvso.source_object_id
    where hcvso.historical_case_version_id = p_historical_case_version_id
    group by hcvso.historical_case_version_id
  )
  insert into private.historical_case_search_units (
    source_key,
    historical_case_version_id,
    historical_case_id,
    source_layer_role,
    unit_type,
    case_code_snapshot,
    case_title_snapshot,
    precedent_type_snapshot,
    precedent_availability_snapshot,
    case_evidence_strength_snapshot,
    case_contains_historical_value_only_content,
    case_personal_information_status,
    source_object_personal_information_status,
    effective_confidentiality_level_id,
    unit_evidence_strength,
    search_text,
    actor_type,
    lesson_kind,
    historical_value_only,
    contamination_risk_level,
    current_authority_disposition,
    responsibility_id,
    decision_id,
    lesson_id,
    generation_strategy_code,
    generation_strategy_version,
    generated_at
  )
  select
    private.historical_case_search_unit_expected_source_key(
      'case_narrative',
      version_record.historical_case_version_id,
      null,
      null,
      null
    ),
    version_record.historical_case_version_id,
    version_record.historical_case_id,
    'historical_precedent',
    'case_narrative',
    version_record.case_code,
    version_record.canonical_title,
    version_record.precedent_type,
    version_record.precedent_availability,
    version_record.evidence_strength,
    version_record.contains_historical_value_only_content,
    version_record.personal_information_status,
    narrative_source_meta.source_object_personal_information_status,
    narrative_source_meta.effective_confidentiality_level_id,
    version_record.evidence_strength,
    version_record.curated_narrative,
    null,
    null,
    null,
    null,
    null,
    null,
    null,
    null,
    'phase_6_governed_search_units',
    '6.4A_v1',
    rebuild_started_at
  from narrative_source_meta
  on conflict (source_key) do update
  set historical_case_version_id = excluded.historical_case_version_id,
      historical_case_id = excluded.historical_case_id,
      case_code_snapshot = excluded.case_code_snapshot,
      case_title_snapshot = excluded.case_title_snapshot,
      precedent_type_snapshot = excluded.precedent_type_snapshot,
