create or replace function private.strictest_knowledge_confidentiality_level_id(p_level_ids bigint[])
returns bigint
language sql
stable
as $$
  with normalized_level_ids as (
    select distinct level_id
    from unnest(coalesce(p_level_ids, '{}'::bigint[])) as level_id
    where level_id is not null
  )
  select kcl.id
  from normalized_level_ids nli
  join public.knowledge_confidentiality_levels kcl
    on kcl.id = nli.level_id
  order by kcl.sort_order desc, kcl.id desc
  limit 1;
$$;

create or replace function private.strictest_personal_information_status(p_statuses text[])
returns text
language sql
immutable
as $$
  select
    case
      when exists (
        select 1
        from unnest(coalesce(p_statuses, '{}'::text[])) as status_value
        where status_value = 'yes'
      ) then 'yes'
      when exists (
        select 1
        from unnest(coalesce(p_statuses, '{}'::text[])) as status_value
        where status_value = 'unknown'
      ) then 'unknown'
      else 'no'
    end;
$$;

