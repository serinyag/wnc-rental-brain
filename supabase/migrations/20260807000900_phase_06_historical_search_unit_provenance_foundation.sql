create or replace function private.rebuild_current_historical_case_search_units()
returns bigint
language plpgsql
as $$
declare
  target_version record;
  generated_unit_total bigint := 0;
begin
  for target_version in
    select hcv.id
    from public.historical_case_versions hcv
    where hcv.governance_status = 'active'
      and hcv.precedent_availability in ('active', 'limited')
    order by hcv.historical_case_id, hcv.version_number
  loop
    generated_unit_total :=
      generated_unit_total + private.rebuild_historical_case_search_units_for_version(target_version.id);
  end loop;

  return generated_unit_total;
end;
$$;

